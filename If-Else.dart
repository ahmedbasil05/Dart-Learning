/*
Topic: If-Else Statement

The if-else statement is used to make decisions in a program.
If the condition is true, the code inside the if block executes.
Otherwise, the code inside the else block executes.
*/

void main() {
  int marks = 76;

  // Check whether the student has passed or failed
  if (marks >= 50) {
    print("Pass");
  } else {
    print("Fail");
  }
}
