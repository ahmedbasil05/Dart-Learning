/*
Topic: Variables and Data Types

Variables are used to store data in memory. Each variable has
a data type that defines the kind of value it can store, such
as text, numbers, decimal values, or true/false values.
*/

void main() {
  String name = "ABC";
  int age = 21;
  double height = 6.0;
  bool isStudent = true;

  print("Name: $name");
  print("Age: $age");
  print("Height: $height");
  print("Is Student: $isStudent");
}
